#!/usr/bin/env python3
"""Regenerate mirror-mappings.txt with a CONSISTENT naming convention.

BUG FIXED: the original mappings flattened names (linuxserver/sonarr -> sonarr)
while rewrite-compose-images.py preserves namespace paths (linuxserver/sonarr
stays). The registry held flat names, so 63+ compose refs would 404 on fresh
pull — breaking the SHTF offline guarantee.

New convention (matches rewrite-compose-images.py make_forgejo_target and
Forgejo's nested-name support):
  source = ghcr.io/linuxserver/sonarr:latest
  target = <REDACTED_HOST>/nicholas/linuxserver/sonarr:latest
  (Docker Hub official images drop the 'library/' prefix; everything else
   keeps its full repo path. Digest-pinned sources keep their digest.)

Sources are gathered from the ORIGINAL compose refs (pre-rewrite) so nothing
is lost. Bootstrap images (forgejo itself + its postgres) and self-built
images (git.${DOMAIN_NAME}/*, netbox:latest-plugins) are excluded by design.
"""
import re
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
MAPPINGS = REPO / ".forgejo" / "workflows" / "mirror-mappings.txt"
ORIG_REF_FILE = pathlib.Path("C:/Dev/original-upstream-refs.txt")

# Images whose builds are handled elsewhere (never mirrored):
# - Forgejo bootstrap image (must stay upstream so registry can cold-boot)
# - Self-built / self-pushed images
BOOTSTRAP = {
    "codeberg.org/forgejo/forgejo:14",
}
SELF_BUILT = {
    "git.${DOMAIN_NAME}/nicholas/dealhound:latest",
    "git.${DOMAIN_NAME}/nicholas/garden-api:latest",
    "git.${DOMAIN_NAME}/nicholas/garden-web:latest",
    "git.${DOMAIN_NAME}/nicholas/userbrowser:latest",
    "netbox:latest-plugins",  # local build from docker-compose.override.yml
    "fnsys/dockhand:latest",  # dockhand is self-maintained (HA add-on builds it)
    "sqlite:latest",          # bogus ref, removed from compose already
    "docker.io/roundcube/roundcube:1.6.9-apache",  # replaced by roundcubemail
    "gcr.io/zenika-hub/alpine-chrome:123",         # replaced by zenika/alpine-chrome
}

# Explicit overrides: corrected upstream refs that don't appear verbatim
# in the original compose history (they were fixed after the rewrite).
OVERRIDES = {
    "docker.io/roundcube/roundcubemail:1.6.9-apache": "<REDACTED_HOST>/nicholas/roundcube/roundcubemail:1.6.9-apache",
    # karakeep chrome was switched to zenika/alpine-chrome:latest (gcr.io
    # zenika-hub:123 tag was deleted upstream); not in original history.
    "zenika/alpine-chrome:latest": "<REDACTED_HOST>/nicholas/zenika/alpine-chrome:latest",
}

def strip_registry(img: str) -> str:
    """Remove registry host prefix, keep repo:tag or repo@digest."""
    m = re.match(r'^([a-zA-Z0-9][a-zA-Z0-9.-]*\.[a-zA-Z]{2,}/)?(.+)$', img)
    return m.group(2) if m else img

def make_target(src: str) -> str:
    """source -> <REDACTED_HOST>/nicholas/<path> (path preserved).

    Digest-pinned sources (src@sha256:...) map to a TAG target
    (:sha256-<12>) because docker push requires a tag; the digest then
    exists in the registry so compose refs that pull by @sha256 resolve.
    """
    repo = strip_registry(src)
    # Docker Hub official images: drop library/
    if repo.startswith("library/"):
        repo = repo[len("library/"):]
    if "@sha256:" in repo:
        name, _, digest = repo.partition("@sha256:")
        return f"<REDACTED_HOST>/nicholas/{name}:sha256-{digest[:12]}"
    return f"<REDACTED_HOST>/nicholas/{repo}"

def load_original_sources() -> list[str]:
    """Unique upstream image refs from pre-rewrite compose files."""
    srcs = set()
    for line in ORIG_REF_FILE.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        img = parts[-1]
        srcs.add(img)
    return sorted(srcs)

def main() -> int:
    sources = load_original_sources()
    excluded = []
    lines = []
    for src in sources:
        if src in BOOTSTRAP or src in SELF_BUILT:
            excluded.append(src)
            continue
        if src in OVERRIDES:
            lines.append(f"{src}\t{OVERRIDES[src]}")
            continue
        tgt = make_target(src)
        lines.append(f"{src}\t{tgt}")
    # Any overrides not present in the source list (e.g. corrected refs)
    for src, tgt in OVERRIDES.items():
        if src not in sources and src not in BOOTSTRAP and src not in SELF_BUILT:
            lines.append(f"{src}\t{tgt}")

    # Write
    header = (
        "# SHTF image mirror mappings: <upstream source>\t<local forgejo target>\n"
        "# Regenerated by scripts/regenerate-mirror-mappings.py — targets PRESERVE\n"
        "# namespace paths (linuxserver/sonarr -> <REDACTED_HOST>/nicholas/linuxserver/sonarr)\n"
        "# matching rewrite-compose-images.py. Bootstrap + self-built images excluded.\n"
        f"# Sources: {len(sources)} | Mapped: {len(lines)} | Excluded: {len(excluded)}\n"
    )
    MAPPINGS.write_text(header + "\n".join(lines) + "\n")
    print(f"Wrote {MAPPINGS} ({len(lines)} mappings)")
    print(f"Excluded ({len(excluded)}):")
    for e in excluded:
        print(f"  - {e}")

    # Sanity: no duplicate targets
    targets = [l.split("\t")[1] for l in lines]
    dupes = {t for t in targets if targets.count(t) > 1}
    if dupes:
        print(f"\n⚠️  DUPLICATE TARGETS: {dupes}")
        return 1
    print("\n✅ No duplicate targets.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
